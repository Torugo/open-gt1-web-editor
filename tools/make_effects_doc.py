"""Write docs/effects.md: every GT-1 effect type and what it models.

Type names and their order come from the parameter table (app/data/gt1.json, built locally by
build_defs.py from your own BOSS TONE STUDIO); descriptions come from app/js/devices/gt1-hints.js,
the same hints the editor shows on hover.

Usage:  python -I tools/make_effects_doc.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
defs = json.load(open(os.path.join(ROOT, "app", "data", "gt1.json"), encoding="utf-8"))["defs"]
hints_js = open(os.path.join(ROOT, "app", "js", "devices", "gt1-hints.js"), encoding="utf-8").read()

# parse `const NAME = { 'KEY': 'value', KEY: "value", ... };` blocks from the hints file
tables = {}
for name, body in re.findall(r"const (\w+) = \{(.*?)\n\};", hints_js, re.S):
    entries = re.findall(r"""(?:'([^']+)'|"([^"]+)"|(\w+))\s*:\s*(?:'([^']*)'|"([^"]*)")""", body)
    tables[name] = {(a or b or c): (d or e) for a, b, c, d, e in entries}

PRETTY = {"TWAH": "T.WAH", "GEQ": "GRAPHIC EQ", "PEQ": "PARAMETRIC EQ", "TONEMODIFY": "TONE MODIFY",
          "GTRSIM": "GUITAR SIM", "ACSIM": "AC.GUITAR SIM", "SLOWGEAR": "SLOW GEAR", "PITCHSHIFTER": "PITCH SHIFTER",
          "AC_PROC": "AC.PROCESSOR", "UNI_V": "UNI-V", "SUBDELAY": "SUB DELAY"}

SECTIONS = [
    ("Preamp (A and B)", "PREAMP_TYPE", "PREAMP"),
    ("OD/DS", "ODDS_TYPE", "ODDS"),
    ("Compressor (COMP block, and FX COMPRESSOR sub types)", "COMP_TYPE", "COMP"),
    ("FX1 / FX2", "FX1_TYPE", "FX"),
    ("Delay", "DELAY_TYPE", "DELAY"),
    ("Chorus", "CHORUS_TYPE", "CHORUS"),
    ("Reverb", "REVERB_TYPE", "REVERB"),
    ("Pedal FX (wah, also the FX SUB WAH types)", "PEDAL_FX_TYPE", "WAH"),
    ("Accel FX", "ACCEL_FX_TYPE", None),
]
SUBS = [
    ("FX LIMITER sub types", "FX1_SUB_TYPE_LIST", "LIMITER", "LIMITER"),
    ("FX TONE MODIFY sub types", "FX1_SUB_TYPE_LIST", "TONEMODIFY", "TONEMODIFY"),
    ("FX AC.PROCESSOR sub types", "FX1_SUB_TYPE_LIST", "AC_PROC", "AC_PROC"),
]

def row(name, desc):
    real = desc.startswith("Models")
    return f"| {PRETTY.get(name, name)} | {'**' + desc + '**' if real else (desc or '—')} |"

out = ["# GT-1 effects", "",
       "Every effect type of the BOSS GT-1, in the order the unit stores them, with what it models.",
       "**Bold** entries model a specific real pedal or amp; the rest are BOSS originals.", "",
       "Source: the *This models …* lines of the BOSS GT-1 Parameter Guide, condensed. The editor shows",
       "the same text when you hover a block or a type. Brand and model names are trademarks of their",
       "owners and are used only to describe the sound.", "",
       "Generated by `tools/make_effects_doc.py` from `app/js/devices/gt1-hints.js`.", ""]
for title, table, hints in SECTIONS:
    out += [f"## {title}", "", "| Type | Models / description |", "|---|---|"]
    h = tables.get(hints, {}) if hints else {}
    for t in defs[table]:
        out.append(row(t["name"], h.get(t["name"], "")))
    out.append("")
for title, table, key, hints in SUBS:
    out += [f"## {title}", "", "| Type | Models / description |", "|---|---|"]
    for t in defs[table][key]:
        out.append(row(t["name"], tables[hints].get(t["name"], "")))
    out.append("")
out += ["Accel FX types are not described in the Parameter Guide, so they have no description here.", ""]

dest = os.path.join(ROOT, "docs", "effects.md")
os.makedirs(os.path.dirname(dest), exist_ok=True)
open(dest, "w", encoding="utf-8", newline="\n").write("\n".join(out))
real = sum(1 for line in out if "| **Models" in line)
print("wrote", dest, "-", real, "types model real gear")
